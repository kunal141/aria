"""
Artifact Engine — Week 8

Converts typed skill output (Pydantic JSON) into formatted, shareable artifacts.
Each skill type has its own renderer. The engine selects the right one by task_type.

Artifact types:
  pr_review  → PRReviewArtifact  (verdict card + issue list + risk + business impact)
  kpi        → KPIArtifact       (executive summary + root cause table + actions)
  general    → PlainArtifact     (passthrough — no formatting)
"""
import json
from typing import Optional


# ─────────────────────────────────────────────────────────────────────────────
# Helpers
# ─────────────────────────────────────────────────────────────────────────────

_SEV_ICON = {
    "critical": "🔴",
    "high":     "🟠",
    "medium":   "🟡",
    "low":      "🟢",
}

_VERDICT_ICON = {
    "approve":           "✅",
    "request_changes":   "❌",
    "needs_discussion":  "💬",
}

_RISK_ICON = {
    "high":   "🔴",
    "medium": "🟡",
    "low":    "🟢",
}

_LIKELIHOOD_ICON = {
    "high":   "🔴",
    "medium": "🟡",
    "low":    "🟢",
}

def _divider(width: int = 54) -> str:
    return "─" * width


# ─────────────────────────────────────────────────────────────────────────────
# PR Review Artifact
# ─────────────────────────────────────────────────────────────────────────────

def _render_pr_review(data: dict, task_id: str) -> str:
    verdict      = data.get("verdict", "unknown")
    risk         = data.get("risk_level", "unknown")
    summary      = data.get("summary", "")
    issues       = data.get("code_issues", [])
    missing      = data.get("missing_tests", [])
    risks        = data.get("deployment_risks", [])
    impact       = data.get("business_impact", "")
    positives    = data.get("positive_observations", [])
    version      = data.get("version", "v1")

    v_icon  = _VERDICT_ICON.get(verdict, "❓")
    r_icon  = _RISK_ICON.get(risk, "❓")

    lines = [
        f"┌{'─' * 52}┐",
        f"│  ARIA PR REVIEW REPORT                              │",
        f"│  task: {task_id[:40]:<40}  │",
        f"├{'─' * 52}┤",
        f"│  VERDICT  {v_icon} {verdict.upper().replace('_', ' '):<40}│",
        f"│  RISK     {r_icon} {risk.upper():<43}│",
        f"├{'─' * 52}┤",
        f"│  {summary[:50]:<50}  │" if len(summary) <= 50 else
        f"│  {summary[:50]}  │",
    ]

    if len(summary) > 50:
        lines.append(f"│  {summary[50:100]:<50}  │")

    lines.append(f"├{'─' * 52}┤")

    # Code issues
    if issues:
        lines.append(f"│  CODE ISSUES ({len(issues)}){'':>35}│")
        for issue in issues:
            sev  = issue.get("severity", "low")
            cat  = issue.get("category", "")
            desc = issue.get("description", "")
            sugg = issue.get("suggestion", "")
            icon = _SEV_ICON.get(sev, "⚪")
            lines.append(f"│  {icon} [{sev}] {cat:<42}│")
            for chunk in [desc[i:i+48] for i in range(0, min(len(desc), 96), 48)]:
                lines.append(f"│    {chunk:<50}│")
            lines.append(f"│    → {sugg[:46]:<46}  │")
    else:
        lines.append(f"│  CODE ISSUES  none{'':>33}│")

    lines.append(f"├{'─' * 52}┤")

    # Missing tests
    if missing:
        lines.append(f"│  MISSING TESTS ({len(missing)}){'':>34}│")
        for t in missing:
            lines.append(f"│  • {t[:48]:<48}  │")
    else:
        lines.append(f"│  MISSING TESTS  none{'':>31}│")

    lines.append(f"├{'─' * 52}┤")

    # Deployment risks
    if risks:
        lines.append(f"│  DEPLOYMENT RISKS ({len(risks)}){'':>31}│")
        for r in risks:
            lines.append(f"│  ⚠ {r[:48]:<48}  │")
    else:
        lines.append(f"│  DEPLOYMENT RISKS  none{'':>28}│")

    lines.append(f"├{'─' * 52}┤")

    # Business impact
    lines.append(f"│  BUSINESS IMPACT{'':>35}│")
    for chunk in [impact[i:i+50] for i in range(0, min(len(impact), 150), 50)]:
        lines.append(f"│  {chunk:<50}  │")

    # Positives
    if positives:
        lines.append(f"├{'─' * 52}┤")
        lines.append(f"│  ✓ WHAT'S GOOD{'':>37}│")
        for p in positives:
            lines.append(f"│  • {p[:48]:<48}  │")

    lines.append(f"└{'─' * 52}┘")
    lines.append(f"  Generated by ARIA skill_registry/pr_review:{version}")

    return "\n".join(lines)


# ─────────────────────────────────────────────────────────────────────────────
# KPI Artifact
# ─────────────────────────────────────────────────────────────────────────────

def _render_kpi(data: dict, task_id: str) -> str:
    summary   = data.get("summary", "")
    causes    = data.get("root_causes", [])
    actions   = data.get("recommended_actions", [])
    needed    = data.get("data_needed", [])
    conf      = data.get("confidence_score", 0.0)
    version   = data.get("version", "v1")

    conf_bar  = "█" * int(conf * 10) + "░" * (10 - int(conf * 10))

    lines = [
        f"┌{'─' * 52}┐",
        f"│  ARIA KPI INVESTIGATION BRIEF                       │",
        f"│  task: {task_id[:40]:<40}  │",
        f"├{'─' * 52}┤",
        f"│  CONFIDENCE  [{conf_bar}] {conf:.0%}{'':>17}│",
        f"├{'─' * 52}┤",
        f"│  SUMMARY{'':>43}│",
    ]

    for chunk in [summary[i:i+50] for i in range(0, min(len(summary), 150), 50)]:
        lines.append(f"│  {chunk:<50}  │")

    lines.append(f"├{'─' * 52}┤")

    # Root causes
    if causes:
        lines.append(f"│  ROOT CAUSE HYPOTHESES ({len(causes)}){'':>27}│")
        for i, c in enumerate(causes, 1):
            hyp  = c.get("hypothesis", "")
            lik  = c.get("likelihood", "low")
            ev   = c.get("evidence", "")
            icon = _LIKELIHOOD_ICON.get(lik, "⚪")
            lines.append(f"│  {i}. {icon} [{lik}]{'':>40}│")
            for chunk in [hyp[i:i+46] for i in range(0, min(len(hyp), 92), 46)]:
                lines.append(f"│     {chunk:<47}  │")
            lines.append(f"│     Evidence: {ev[:37]:<37}  │")

    lines.append(f"├{'─' * 52}┤")

    # Recommended actions
    if actions:
        lines.append(f"│  RECOMMENDED ACTIONS{'':>31}│")
        for a in actions:
            lines.append(f"│  → {a[:48]:<48}  │")

    lines.append(f"├{'─' * 52}┤")

    # Data needed
    if needed:
        lines.append(f"│  DATA TO PULL{'':>38}│")
        for d in needed:
            lines.append(f"│  📊 {d[:47]:<47}  │")

    lines.append(f"└{'─' * 52}┘")
    lines.append(f"  Generated by ARIA skill_registry/kpi:{version}")

    return "\n".join(lines)


# ─────────────────────────────────────────────────────────────────────────────
# Plain Artifact (passthrough for unformatted outputs)
# ─────────────────────────────────────────────────────────────────────────────

def _render_plain(skill_output: str, task_type: str, task_id: str) -> str:
    return (
        f"ARIA — {task_type.upper().replace('_', ' ')}\n"
        f"task: {task_id}\n"
        f"{_divider()}\n"
        f"{skill_output}"
    )


# ─────────────────────────────────────────────────────────────────────────────
# Manager / Leadership summary renderers (audience-aware — Week 13)
# ─────────────────────────────────────────────────────────────────────────────

def _render_manager_summary(data: dict, task_type: str, task_id: str) -> str:
    """
    Compact summary for manager audience.
    3–5 lines: verdict/status + risk + top action + business impact.
    Same underlying data — different depth and tone.
    """
    lines = [f"ARIA — {task_type.upper().replace('_', ' ')} SUMMARY  [{task_id[:8]}]", ""]

    if task_type == "pr_review":
        verdict = data.get("verdict", "unknown").replace("_", " ").title()
        risk    = data.get("risk_level", "unknown").upper()
        summary = data.get("summary", "")
        impact  = data.get("business_impact", "")
        issues  = data.get("code_issues", [])
        top_issue = issues[0].get("description", "") if issues else "None found"

        lines += [
            f"Verdict        : {verdict}",
            f"Risk           : {risk}",
            f"Summary        : {summary}",
            f"Top issue      : {top_issue}",
            f"Business impact: {impact}",
        ]

    elif task_type == "kpi":
        summary  = data.get("summary", "")
        conf     = data.get("confidence_score", 0.0)
        causes   = data.get("root_causes", [])
        actions  = data.get("recommended_actions", [])
        top_cause  = causes[0].get("hypothesis", "") if causes else "Unknown"
        top_action = actions[0] if actions else "Investigate further"

        lines += [
            f"Summary        : {summary}",
            f"Confidence     : {conf:.0%}",
            f"Top root cause : {top_cause}",
            f"Immediate action: {top_action}",
        ]

    else:
        lines.append(str(data))

    return "\n".join(lines)


def _render_leadership_brief(data: dict, task_type: str, task_id: str) -> str:
    """
    2–3 line executive brief for leadership audience.
    What happened. Risk. What to decide.
    """
    if task_type == "pr_review":
        verdict = data.get("verdict", "unknown").replace("_", " ").title()
        risk    = data.get("risk_level", "unknown")
        impact  = data.get("business_impact", "Not specified")
        return (
            f"PR Review [{task_id[:8]}] — {verdict} | Risk: {risk.upper()}\n"
            f"Impact: {impact}\n"
            f"Action required: {'Yes — review issues before merge' if verdict != 'approve' else 'No — safe to proceed'}"
        )

    elif task_type == "kpi":
        summary = data.get("summary", "")
        conf    = data.get("confidence_score", 0.0)
        actions = data.get("recommended_actions", [])
        top_action = actions[0] if actions else "Further investigation needed"
        return (
            f"KPI Alert [{task_id[:8]}] — {summary}\n"
            f"Confidence: {conf:.0%} | Recommended: {top_action}"
        )

    return f"ARIA [{task_id[:8]}] — {str(data)[:120]}"


# ─────────────────────────────────────────────────────────────────────────────
# Public API
# ─────────────────────────────────────────────────────────────────────────────

def render_artifact(
    task_type: str,
    skill_output: Optional[str],
    task_id: str,
    audience: Optional[str] = None,
) -> str:
    """
    Convert raw skill_output (JSON string) into a formatted artifact.

    audience controls rendering depth:
      developer  (default) → full technical card with all details
      manager              → compact 5-line summary
      leadership           → 2-line executive brief
    """
    if not skill_output or skill_output.startswith("[Week"):
        return _render_plain(skill_output or "[no output]", task_type, task_id)

    try:
        data = json.loads(skill_output)
    except json.JSONDecodeError:
        return _render_plain(skill_output, task_type, task_id)

    if audience == "leadership":
        return _render_leadership_brief(data, task_type, task_id)

    if audience == "manager":
        return _render_manager_summary(data, task_type, task_id)

    # Default: developer — full card
    if task_type == "pr_review":
        return _render_pr_review(data, task_id)
    elif task_type == "kpi":
        return _render_kpi(data, task_id)
    else:
        return _render_plain(skill_output, task_type, task_id)
