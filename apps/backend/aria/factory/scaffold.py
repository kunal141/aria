"""
Agent Scaffolder — Week 22

scaffold_agent(spec) produces a ready-to-run Python module stub for a new
specialist agent. The stub follows the same pattern as skill_nodes.py:
  - ARIAState in, dict out
  - Skill called through skill_registry
  - guard_loop() called first
  - _routing_kwargs() pattern for data_sensitivity / audience

The output is a Python source string — the Agent Factory writes it to
aria/agents/<name>.py and registers it in the skill registry.

In V2 this runs inside a sandboxed subprocess with restricted permissions.
In V1 the output is returned as a string for human review before writing.
"""
import textwrap
from aria.factory.agent_spec import AgentSpec


def scaffold_agent(spec: AgentSpec) -> str:
    """
    Generate a Python agent node module from an AgentSpec.
    Returns the module source as a string.

    The generated code is a ready-to-merge stub:
      - Imports are correct
      - Node function signature matches the ARIAState contract
      - Placeholder skill call uses the first registered capability
      - guard_loop() is wired
      - Steps are tracked in steps_completed
    """
    module_name = spec.name.replace("-", "_")
    primary_skill = spec.capabilities[0].skill_name if spec.capabilities else "general"
    skill_names = ", ".join(c.skill_name for c in spec.capabilities)

    source = textwrap.dedent(f'''\
        """
        {spec.role} Agent — generated by ARIA Agent Factory
        Agent: {spec.name}  Version: {spec.version}
        Goal:  {spec.goal}

        Capabilities: {skill_names}
        Status: {spec.status}
        Owner:  {spec.owner}

        This module was scaffolded automatically. Review before promotion to active.
        DO NOT modify the function signature or guard_loop call.
        """
        from aria.state import ARIAState
        from aria.skills import skill_registry
        from aria.runtime.harness import guard_loop


        def {module_name}_node(state: ARIAState) -> dict:
            guard_loop(state["steps_completed"], state["task_id"])

            # TODO: import and call the appropriate skill input/run function
            # Primary capability: {primary_skill}
            # Replace this placeholder with the real skill invocation:
            #
            #   from aria.skills.{primary_skill}_skill import {_to_class(primary_skill)}Input, run as {primary_skill}_run
            #   result = {primary_skill}_run({_to_class(primary_skill)}Input(
            #       raw_input=state["raw_input"],
            #       task_id=state["task_id"],
            #       data_sensitivity=state.get("data_sensitivity") or "internal",
            #       audience=state.get("audience") or "developer",
            #   ))

            return {{
                "skill_name":      "{spec.name}:{spec.version}:placeholder",
                "skill_output":    f"[{spec.name}] scaffolded agent — implement skill call above",
                "steps_completed": state["steps_completed"] + ["{module_name}_node"],
            }}
    ''')
    return source


# ── Helpers ───────────────────────────────────────────────────────────────────

def _to_class(skill_name: str) -> str:
    """Convert 'pr_review' → 'PRReview', 'kpi' → 'KPI', 'ci_cd' → 'CICD'."""
    _overrides = {
        "kpi":         "KPI",
        "ci_cd":       "CICD",
        "pr_review":   "PRReview",
        "qa":          "QA",
        "test_review": "TestReview",
        "jira":        "Jira",
    }
    return _overrides.get(skill_name, skill_name.replace("_", " ").title().replace(" ", ""))
