"""
Agent Scaffolder — Week 22

scaffold_agent(spec) produces a ready-to-run Python module stub for a new
specialist agent. The stub follows the same pattern as skill_nodes.py:
  - ARIAState in, dict out
  - Skill called through skill_registry
  - guard_loop() called first
  - _routing_kwargs() pattern for data_sensitivity / audience

The output is a Python source string — the Agent Factory writes it to
aria/agents/<name>.py and registers it in the skill registry.

In V2 this runs inside a sandboxed subprocess with restricted permissions.
In V1 the output is returned as a string for human review before writing.
"""
import textwrap
from aria.factory.agent_spec import AgentSpec


def scaffold_agent(spec: AgentSpec) -> str:
    """
    Generate a Python agent node module from an AgentSpec.
    Returns the module source as a string.

    The generated code is a ready-to-merge stub:
      - Imports are correct
      - Node function signature matches the ARIAState contract
      - Placeholder skill call uses the first registered capability
      - guard_loop() is wired
      - Steps are tracked in steps_completed

    Safety guarantees for generated Python:
      - spec.name is validated as a Python identifier (see AgentSpec.name validator)
      - string fields in the docstring are escaped with _safe_embed() (handles triple-quotes)
      - string VALUES in the return dict are generated with repr() so quotes,
        backslashes, and other special chars in version/name/etc. can never
        produce an unterminated literal
      - primary_skill in comment lines is sanitised with _safe_comment() so a
        newline in a capability skill_name cannot break out of the comment
    """
    module_name   = spec.name.replace("-", "_")
    primary_skill = spec.capabilities[0].skill_name if spec.capabilities else "general"
    skill_names   = ", ".join(c.skill_name for c in spec.capabilities)

    # Values used as Python string literals: produce them with repr() so any
    # character in version/name/owner is safe regardless of quotes or backslashes.
    skill_name_literal  = repr(f"{spec.name}:{spec.version}:placeholder")
    skill_output_literal = repr(f"[{spec.name}] scaffolded agent — implement skill call above")

    # Values used in comment lines: strip newlines so they cannot break indentation.
    safe_skill      = _safe_comment(primary_skill)
    safe_skill_cls  = _safe_comment(_to_class(primary_skill))

    source = textwrap.dedent(f'''\
        """
        {_safe_embed(spec.role)} Agent — generated by ARIA Agent Factory
        Agent: {_safe_embed(spec.name)}  Version: {_safe_embed(spec.version)}
        Goal:  {_safe_embed(spec.goal)}

        Capabilities: {_safe_embed(skill_names)}
        Status: {_safe_embed(spec.status)}
        Owner:  {_safe_embed(spec.owner)}

        This module was scaffolded automatically. Review before promotion to active.
        DO NOT modify the function signature or guard_loop call.
        """
        from aria.state import ARIAState
        from aria.skills import skill_registry
        from aria.runtime.harness import guard_loop


        def {module_name}_node(state: ARIAState) -> dict:
            guard_loop(state["steps_completed"], state["task_id"])

            # TODO: import and call the appropriate skill input/run function
            # Primary capability: {safe_skill}
            # Replace this placeholder with the real skill invocation:
            #
            #   from aria.skills.{safe_skill}_skill import {safe_skill_cls}Input, run as {safe_skill}_run
            #   result = {safe_skill}_run({safe_skill_cls}Input(
            #       raw_input=state["raw_input"],
            #       task_id=state["task_id"],
            #       data_sensitivity=state.get("data_sensitivity") or "internal",
            #       audience=state.get("audience") or "developer",
            #   ))

            return {{
                "skill_name":      {skill_name_literal},
                "skill_output":    {skill_output_literal},
                "steps_completed": state["steps_completed"] + ["{module_name}_node"],
            }}
    ''')
    return source


# ── Helpers ───────────────────────────────────────────────────────────────────

def _safe_embed(s: str) -> str:
    """
    Make s safe for embedding inside a triple-double-quoted, indented docstring.

    Three transformations, always applied in this order:
    1. Double all backslashes first — prevents \\u, \\n, etc. from being
       interpreted as escape sequences when Python compiles the docstring.
    2. Escape triple-double-quotes — prevents premature docstring close.
    3. Replace newlines with spaces — prevents injected newlines from creating
       zero-indented lines that break textwrap.dedent (which removes the common
       leading whitespace; a 0-indent line reduces the common prefix to nothing).
    """
    return (
        s
        .replace('\\', '\\\\')       # step 1: double backslashes (must be first)
        .replace('"""', '\\"\\"\\"')  # step 2: escape triple-double-quotes
        .replace('\n', ' ')           # step 3: collapse newlines
        .replace('\r', ' ')
    )


def _safe_comment(s: str) -> str:
    """Strip newlines so the value is safe inside a single-line # comment."""
    return s.replace("\n", " ").replace("\r", " ")


def _to_class(skill_name: str) -> str:
    """Convert 'pr_review' → 'PRReview', 'kpi' → 'KPI', 'ci_cd' → 'CICD'."""
    _overrides = {
        "kpi":         "KPI",
        "ci_cd":       "CICD",
        "pr_review":   "PRReview",
        "qa":          "QA",
        "test_review": "TestReview",
        "jira":        "Jira",
    }
    return _overrides.get(skill_name, skill_name.replace("_", " ").title().replace(" ", ""))
